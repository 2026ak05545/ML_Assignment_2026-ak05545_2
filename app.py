
import streamlit as st
import pandas as pd
import numpy as np
import joblib
import os
from sklearn.metrics import (
    accuracy_score, roc_auc_score, precision_score, recall_score,
    f1_score, matthews_corrcoef, confusion_matrix, classification_report
)
import matplotlib.pyplot as plt
import seaborn as sns

st.set_page_config(page_title="Adult Income Classification", page_icon="📊", layout="wide")
st.title("Machine Learning Classification Model Comparison")
st.write("Compare five trained classifiers on an uploaded labelled test CSV.")
st.info("Upload test data containing the 14 input features and the target column 'income'. Models are loaded from the repository; the app does not retrain them.")

MODEL_DIR = "models"
model_files = {
    "Logistic Regression": "logistic_regression.joblib",
    "Decision Tree": "decision_tree.joblib",
    "K-Nearest Neighbors": "k_nearest_neighbors.joblib",
    "Gaussian Naive Bayes": "gaussian_naive_bayes.joblib",
    "Support Vector Machine": "support_vector_machine.joblib"
}

@st.cache_resource
def load_models():
    loaded = {}
    for name, filename in model_files.items():
        path = os.path.join(MODEL_DIR, filename)
        if os.path.exists(path):
            loaded[name] = joblib.load(path)
    return loaded

models = load_models()
if not models:
    st.error("No saved models found. Ensure the 'models' folder is included in the GitHub repository.")
    st.stop()

uploaded_file = st.file_uploader("Upload labelled test dataset (CSV)", type=["csv"])
if uploaded_file is not None:
    data = pd.read_csv(uploaded_file)
    st.subheader("Uploaded dataset preview")
    st.dataframe(data.head(10), use_container_width=True)

    target = "income"
    if target not in data.columns:
        st.error("The uploaded CSV must contain the target column 'income'.")
        st.stop()

    y_true = data[target].astype(str).str.strip().str.replace(".", "", regex=False)
    y_true = y_true.map({"<=50K": 0, ">50K": 1})
    if y_true.isna().any():
        st.error("Target values must be <=50K or >50K.")
        st.stop()

    X = data.drop(columns=[target])
    selected_model = st.selectbox("Select classification model", list(models.keys()))
    pipeline = models[selected_model]

    required_features = list(pipeline.named_steps["preprocessor"].feature_names_in_)
    missing = [c for c in required_features if c not in X.columns]
    if missing:
        st.error(f"Missing required input features: {missing}")
        st.stop()

    X = X[required_features]
    y_pred = pipeline.predict(X)
    y_prob = pipeline.predict_proba(X)[:, 1]

    metrics = {
        "Accuracy": accuracy_score(y_true, y_pred),
        "AUC": roc_auc_score(y_true, y_prob),
        "Precision": precision_score(y_true, y_pred, zero_division=0),
        "Recall": recall_score(y_true, y_pred, zero_division=0),
        "F1 Score": f1_score(y_true, y_pred, zero_division=0),
        "MCC": matthews_corrcoef(y_true, y_pred)
    }

    st.subheader(f"Evaluation metrics: {selected_model}")
    cols = st.columns(6)
    for col, (name, value) in zip(cols, metrics.items()):
        col.metric(name, f"{value:.4f}")

    st.subheader("Confusion matrix")
    cm = confusion_matrix(y_true, y_pred, labels=[0, 1])
    fig, ax = plt.subplots(figsize=(5, 4))
    sns.heatmap(cm, annot=True, fmt="d", cmap="Blues",
                xticklabels=["<=50K", ">50K"],
                yticklabels=["<=50K", ">50K"], ax=ax)
    ax.set_xlabel("Predicted")
    ax.set_ylabel("Actual")
    st.pyplot(fig)

    st.subheader("Classification report")
    report = classification_report(
        y_true, y_pred, target_names=["<=50K", ">50K"],
        output_dict=True, zero_division=0
    )
    st.dataframe(pd.DataFrame(report).transpose(), use_container_width=True)

    st.subheader("Prediction preview")
    output = X.copy()
    output["Actual income"] = y_true.map({0: "<=50K", 1: ">50K"})
    output["Predicted income"] = pd.Series(y_pred, index=X.index).map({0: "<=50K", 1: ">50K"})
    output["Probability of >50K"] = y_prob
    st.dataframe(output.head(50), use_container_width=True)
else:
    st.warning("Please upload test_data.csv generated by the Colab notebook.")
    st.caption("The app evaluates the uploaded labelled test set using the selected saved model.")
